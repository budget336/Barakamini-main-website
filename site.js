// "10 bags cement", "nails 2kg", "- foam x3" → product + quantity, matched against today's list.
const LIST_NOISE = /\b(pcs?|pieces?|kgs?|bags?|m|mtrs?|metres?|meters?|rolls?|sheets?|litres?|ltrs?|pairs?|box(es)?|sets?|of|x|na|and)\b/g;
function parseList(text){
  return text.split(/\n|,|;/).map(line => line.replace(/^[\s\-*•\d]+[.)]\s+/, '').trim()).filter(Boolean).slice(0, 40).map(line => {
    const num = line.match(/(\d+(?:[.,]\d+)?)/);
    const qty = num ? Math.max(0.5, Math.min(10000, Number(num[1].replace(',', '.')))) : 1;
    const words = line.toLowerCase().replace(/[×*]/g, ' ').replace(/\d+(?:[.,]\d+)?/g, ' ').replace(LIST_NOISE, ' ')
      .split(/[^a-z0-9]+/).filter(w => w.length >= 3);
    let best = null, bestScore = 0;
    PRODUCTS.forEach(p => {
      const name = p.name.toLowerCase();
      const score = words.reduce((s, w) => s + (name.includes(w) || (w.endsWith('s') && name.includes(w.slice(0, -1))) ? w.length : 0), 0);
      if (score > bestScore) { best = p; bestScore = score; }
    });
    return { line, qty, product: best };
  });
}
