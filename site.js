function applyLang(){
  document.documentElement.lang = LANG;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    if (el.dataset.en === undefined) el.dataset.en = el.textContent;
    el.textContent = LANG === 'sw' ? (SW_DICT[el.dataset.i18n] || el.dataset.en) : el.dataset.en;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('.word-swap').forEach(el => {
    if (el.dataset.en === undefined) el.dataset.en = el.textContent.trim();
    el.textContent = t(el.dataset.en);
  });
  document.querySelectorAll('.lang-btn').forEach(b => { b.textContent = LANG === 'sw' ? 'English' : 'Kiswahili'; });
}
function toggleLang(){
  LANG = LANG === 'sw' ? 'en' : 'sw';
  try { localStorage.setItem('baraka_lang', LANG); } catch (e) {}
  applyLang();
  renderBranch(); renderCatTabs(); renderProducts(); renderItemGrid(); renderTierGrid(); fillFabricSelect(); updateCalc(); saveReservation(); renderSiteInfo();
}

