/* ================= TRACK MY ORDER ================= */
const TRACK_STEPS = {
  reservation: [['new', 'Received'], ['confirmed', 'Confirmed'], ['collected', 'Collected']],
  visit: [['new', 'Received'], ['confirmed', 'We called you'], ['collected', 'Done']],
  job: [['new', 'Received'], ['measured', 'Measured'], ['in_progress', 'Being made'], ['ready', 'Ready'], ['collected', 'Collected']],
  layaway: [['active', 'Paying'], ['completed', 'Paid & collected']],
  delivery: [['pending', 'To deliver'], ['out', 'On the way'], ['delivered', 'Delivered']],
};
const TRACK_NAMES = { reservation: 'Reservation ', visit: 'Measuring visit ', job: 'Job ', layaway: 'Lipa pole pole ', delivery: 'Delivery ' };
function openTrack(){
  scrollToId('track');
  setTimeout(() => document.querySelector('#track input[name=ref]')?.focus({ preventScroll: true }), 400);
}
async function runTrack(form){
  const out = document.getElementById('trackResult');
  out.textContent = t('Checking…');
  try {
    const r = await rpc('track_order', { p_ref: form.elements.ref.value, p_phone: form.elements.phone.value });
    const steps = TRACK_STEPS[r.type] || [];
    const at = steps.findIndex(s => s[0] === r.status);
    const date = (d) => d ? new Date(String(d).slice(0, 10) + 'T12:00:00').toLocaleDateString(LANG === 'sw' ? 'sw-KE' : 'en-KE', { weekday: 'short', day: 'numeric', month: 'short' }) : '';
    const money = (n) => `KES ${Math.round(Number(n) || 0).toLocaleString()}`;
    const owed = r.total != null ? Math.max(0, Number(r.total) - Number(r.paid || 0)) : 0;
    const items = Array.isArray(r.items) ? r.items.map(i => `${Number(i.quantity)} × ${esc(i.name)}`).join(', ') : esc(r.items || '');
    out.innerHTML = `<b>${esc(t(TRACK_NAMES[r.type] || ''))}${esc(r.ref)}</b>${r.title ? ' · ' + esc(r.title) : ''}${r.branch ? ` · ${esc(r.branch)}` : ''}
      ${r.status === 'cancelled' ? `<div class="track-steps"><span class="now">${esc(t('Cancelled'))}</span></div>`
        : `<div class="track-steps">${steps.map((s, i) => `<span class="${i < at ? 'done' : i === at ? 'now' : ''}">${esc(t(s[1]))}</span>`).join('')}</div>`}
      ${items ? `<div>${items}</div>` : ''}
      ${r.total != null ? `<div>${esc(t('Paid'))} ${money(r.paid)}${owed > 0 ? ` · <b>${esc(t('Balance'))} ${money(owed)}</b>` : ''}</div>` : ''}
      ${r.due ? `<div>${esc(t(r.type === 'job' ? 'Ready by' : 'Due'))}: ${esc(date(r.due))}</div>` : ''}
      ${r.scheduled ? `<div>${esc(t('Delivery day'))}: ${esc(date(r.scheduled))}</div>` : ''}`;
  } catch (err) {
    out.textContent = err.code === 'NOT_FOUND' ? t('We could not find that. Check the number and use the phone you gave us.')
      : t('Could not check right now — please try again or WhatsApp us.');
  }
}

/* ================= REVIEWS (link sent by the shop) ================= */
let REVIEW_TOKEN = null, REVIEW_STARS = 0;
async function startReview(){
  const params = new URLSearchParams(location.search);
  REVIEW_TOKEN = params.get('review');
  if (!REVIEW_TOKEN) return;
  // Keep the private link out of the address bar and browser history.
  try { history.replaceState(null, '', location.pathname + location.hash); } catch (e) {}
  let who;
  try { who = await rpc('review_customer', { p_token: REVIEW_TOKEN }); }
  catch (e) { return openSiteModal(t('Rate us'), `<p style="font-size:14px;margin:12px 0;">${esc(t('This review link is not valid. Ask the shop for a new one.'))}</p>`); }
  if (who.already) return openSiteModal(t('Rate us'), `<p style="font-size:14px;margin:12px 0;">${esc(t('You already sent a review recently — asante!'))}</p>`);
  showReviewForm(who.first_name);
}
function showReviewForm(name, message, comment){
  openSiteModal(t('Rate us'), `
    <p style="font-size:15px;margin:10px 0 0;">${esc(t('How was your experience,'))} ${esc(name || '')}?</p>
    <div class="stars-input" role="radiogroup" aria-label="Rating">${[1, 2, 3, 4, 5].map(n =>
      `<button type="button" role="radio" aria-checked="${n === REVIEW_STARS}" aria-label="${n}" class="${n <= REVIEW_STARS ? 'on' : ''}" onclick="REVIEW_STARS=${n}; showReviewForm(${esc(JSON.stringify(name || ''))}, '', document.getElementById('rvText').value)">★</button>`).join('')}</div>
    <div class="res-field"><label for="rvText">${esc(t('Tell others about it (optional)'))}</label><textarea id="rvText" rows="4" maxlength="600">${esc(comment || '')}</textarea></div>
    ${message ? `<div class="res-err">${esc(message)}</div>` : ''}
    <button type="button" class="btn-gold-full press" id="rvSend" onclick="sendReview(${esc(JSON.stringify(name || ''))})">${esc(t('Send review'))}</button>`);
}
async function sendReview(name){
  const comment = document.getElementById('rvText').value;
  if (!REVIEW_STARS) return showReviewForm(name, t('Please choose 1 to 5 stars.'), comment);
  document.getElementById('rvSend').disabled = true;
  try {
    await rpc('submit_review', { p_token: REVIEW_TOKEN, p_rating: REVIEW_STARS, p_comment: comment });
    openSiteModal(t('Rate us'), `<p style="font-size:15px;margin:14px 0;">${esc(t('Asante! Your review will appear once the shop has seen it.'))}</p>`);
  } catch (err) {
    if (err.code === 'ALREADY') return openSiteModal(t('Rate us'), `<p style="font-size:14px;margin:12px 0;">${esc(t('You already sent a review recently — asante!'))}</p>`);
    showReviewForm(name, t('Could not send. Please WhatsApp us instead.'), comment);
  }
}

